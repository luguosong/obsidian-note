package com.luguosong.basicsyntax.operator;

/**
 * 算术运算符：基本四则运算 +、-、*。
 * 对应笔记：[[基本语法]] → 运算符 → 算术运算符
 */
public class ArithmeticBasicDemo {

    public static void main(String[] args) {
        int a = 10, b = 3;
        System.out.println(a + b);   // 13
        System.out.println(a - b);   // 7
        System.out.println(a * b);   // 30
    }
}
